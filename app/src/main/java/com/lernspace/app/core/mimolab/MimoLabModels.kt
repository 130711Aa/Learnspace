package com.lernspace.app.core.mimolab

import java.util.UUID

/**
 * Standard STEM Subjects recognized in Mimo Lab.
 */
enum class MimoSubject(val displayName: String, val badgeColorHex: String, val chipLabel: String) {
    FISIKA("Fisika & Mekanika", "#0284C7", "Fisika"),
    KALKULUS("Kalkulus & Aljabar", "#7C3AED", "Kalkulus"),
    TERMODINAMIKA("Termodinamika", "#EA580C", "Termo"),
    ELEKTRO("Elektro & Magnet", "#059669", "Elektro"),
    KIMIA("Kimia & Partikel", "#DB2777", "Kimia"),
    BIOLOGI("Biologi & Genetika", "#16A34A", "Biologi"),
    UMUM("Sains Umum", "#475569", "Umum");

    companion object {
        fun fromString(value: String): MimoSubject {
            val upper = value.uppercase()
            return entries.firstOrNull { upper.contains(it.name) || upper.contains(it.chipLabel.uppercase()) }
                ?: if (upper.contains("CALCULUS") || upper.contains("MATH") || upper.contains("INTEGRAL")) KALKULUS
                else if (upper.contains("PHYSIC") || upper.contains("FORCE") || upper.contains("GERAK")) FISIKA
                else if (upper.contains("THERMO") || upper.contains("HEAT") || upper.contains("PANAS")) TERMODINAMIKA
                else if (upper.contains("ELECTRIC") || upper.contains("CIRCUIT") || upper.contains("MAGNET") || upper.contains("OHM")) ELEKTRO
                else if (upper.contains("CHEM") || upper.contains("ATOM") || upper.contains("REAKSI") || upper.contains("BOHR") || upper.contains("TITRASI")) KIMIA
                else if (upper.contains("BIO") || upper.contains("GENET") || upper.contains("MENDEL") || upper.contains("PUNNETT")) BIOLOGI
                else UMUM
        }
    }
}

/**
 * Represents a single interactive STEM simulation generated by Mimo AI or shared in the Community Lab.
 */
data class MimoSimulation(
    val id: String = UUID.randomUUID().toString(),
    val title: String,
    val subject: MimoSubject,
    val conceptTopic: String,
    val description: String,
    val htmlContent: String,
    val isFavorite: Boolean = false,
    val isCommunityOrigin: Boolean = false,
    val authorName: String = "Mimo AI",
    val likesCount: Int = 0,
    val viewsCount: Int = 0,
    val createdAt: Long = System.currentTimeMillis()
)
